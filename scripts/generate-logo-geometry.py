"""Generates src/lib/brand/geometry.ts (TRC Monolith mark + outlined wordmarks).
Run from website/: python scripts/generate-logo-geometry.py  (needs fonttools)
Then: node scripts/generate-brand-assets.mjs
"""
import os, re
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT=os.path.join(ROOT,'assets-source','fonts','BarlowCondensed-SemiBold.ttf')
def text_path(s, cap_h=100.0, tracking=0.0):
    f=TTFont(FONT); gs=f.getGlyphSet(); cmap=f.getBestCmap(); hmtx=f['hmtx']
    upm=f['head'].unitsPerEm; cap=f['OS/2'].sCapHeight; sc=cap_h/cap
    pen=SVGPathPen(gs); bp=BoundsPen(gs); x=0.0
    for i,ch in enumerate(s):
        g=cmap[ord(ch)]
        t=(sc,0,0,-sc,x,cap_h)
        gs[g].draw(TransformPen(pen,t)); gs[g].draw(TransformPen(bp,t))
        x+=hmtx[g][0]*sc + (tracking*upm*sc if i<len(s)-1 else 0)
    d=pen.getCommands()
    d=re.sub(r'-?\d+\.\d+', lambda m: f"{float(m.group()):.2f}".rstrip('0').rstrip('.'), d)
    xmin,ymin,xmax,ymax=bp.bounds
    return d, round(xmin,2), round(ymin,2), round(xmax,2), round(ymax,2)
full=text_path('T R CONSTRUCTIONS', tracking=0.08)
cons=text_path('CONSTRUCTIONS', tracking=0.03)
out=f'''/**
 * TRC Monolith — single source of truth for the T R Constructions identity.
 * Generated by scripts/generate-logo-geometry.py. Edit with care: the SVG logo components
 * and the Three.js monolith both read these coordinates.
 *
 * Construction (units, cap height = 40, y grows downward):
 *   T = BEAM (accent slab, 30 x 8) resting on a COLUMN (10 x 32)  -> post and beam
 *   R = stem + square bowl with an 8 x 8 counter + a diagonal BRACE leg
 *   C = lipped CHANNEL section (spine 10, flanges 8, lips 6 x 4)  -> C-section steel
 *   Joints between letters = 4 units. Verticals 10, horizontals 8.
 */
export type Pt = readonly [number, number];

export interface MarkPart {{
  id: "beam" | "column" | "brace" | "channel";
  letter: "T" | "R" | "C";
  /** structural reading of the part, used in the hero "exploded" view */
  role: string;
  tone: "accent" | "primary";
  outline: readonly Pt[];
  holes?: readonly (readonly Pt[])[];
}}

export const MARK_WIDTH = 98;
export const MARK_HEIGHT = 40;

export const MARK_PARTS: readonly MarkPart[] = [
  {{
    id: "beam",
    letter: "T",
    role: "Beam",
    tone: "accent",
    outline: [[0, 0], [30, 0], [30, 8], [0, 8]],
  }},
  {{
    id: "column",
    letter: "T",
    role: "Column",
    tone: "primary",
    outline: [[10, 8], [20, 8], [20, 40], [10, 40]],
  }},
  {{
    id: "brace",
    letter: "R",
    role: "Braced frame",
    tone: "primary",
    outline: [[34, 0], [62, 0], [62, 24], [58, 24], [66, 40], [56, 40], [48, 24], [44, 24], [44, 40], [34, 40]],
    holes: [[[44, 8], [52, 8], [52, 16], [44, 16]]],
  }},
  {{
    id: "channel",
    letter: "C",
    role: "Channel section",
    tone: "primary",
    outline: [[70, 0], [98, 0], [98, 12], [92, 12], [92, 8], [80, 8], [80, 32], [92, 32], [92, 28], [98, 28], [98, 40], [70, 40]],
  }},
];

/** Single-path T (beam + column) used for one-colour artwork, so no seam appears. */
export const T_SOLID: readonly Pt[] = [[0, 0], [30, 0], [30, 8], [20, 8], [20, 40], [10, 40], [10, 8], [0, 8]];

export function toPath(points: readonly Pt[]): string {{
  return `M${{points.map(([x, y]) => `${{x}} ${{y}}`).join("L")}}Z`;
}}

export function partPath(part: MarkPart): string {{
  return [part.outline, ...(part.holes ?? [])].map(toPath).join("");
}}
'''
open(os.path.join(ROOT,'src','lib','brand','geometry.ts'),'w',encoding='utf-8').write(out)
